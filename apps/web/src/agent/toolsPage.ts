/**
 * The shipped skill's tool reference (P6-08, ADR-0087 §7):
 * `apps/desktop/skill/extrudo/references/tools.md`, written by
 * `pnpm api:generate` from the tools' own schemas, so it can't drift from what
 * the server lists. `skill.test.ts` fails when the file on disk is stale.
 */
import { CHANGE_TOOLS, type TOOL_NAMES, toolDefinitions } from './schemas';

export const TOOLS_PAGE_PATH = 'apps/desktop/skill/extrudo/references/tools.md';

interface JsonSchema {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  items?: JsonSchema | JsonSchema[];
  prefixItems?: JsonSchema[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  description?: string;
  default?: unknown;
  additionalProperties?: JsonSchema | boolean;
}

/** A schema as one short type, the way the API reference writes them. */
function typeOf(schema: JsonSchema): string {
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map(typeOf).join(' | ');
  if (schema.prefixItems) return `[${schema.prefixItems.map(typeOf).join(', ')}]`;
  if (schema.type === 'array' && schema.items && !Array.isArray(schema.items)) {
    const item = typeOf(schema.items);
    return item.includes(' ') ? `(${item})[]` : `${item}[]`;
  }
  if (schema.type === 'object') {
    if (!schema.properties) return 'object';
    const fields = Object.entries(schema.properties).map(
      ([name, inner]) => `${name}${schema.required?.includes(name) ? '' : '?'}: ${typeOf(inner)}`,
    );
    return `{ ${fields.join(', ')} }`;
  }
  return Array.isArray(schema.type) ? schema.type.join(' | ') : (schema.type ?? 'any');
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function shapes(schema: JsonSchema): string[] {
  const union = schema.anyOf ?? schema.oneOf ?? [];
  return union.map((shape) => {
    const name = shape.properties?.shape?.const;
    const fields = Object.entries(shape.properties ?? {})
      .filter(([field]) => field !== 'shape')
      .map(
        ([field, inner]) =>
          `\`${field}${shape.required?.includes(field) ? '' : '?'}\` ${typeOf(inner)}`,
      );
    return `- \`${String(name)}\`: ${fields.join(', ')}. ${shape.description ?? ''}`.trimEnd();
  });
}

export function toolsPage(): string {
  const lines = [
    '# Tools',
    '',
    "<!-- Generated by `pnpm api:generate` from the tools' schemas: do not edit. -->",
    '',
    'Every tool the Extrudo MCP server lists, with its inputs. Tools marked',
    '**changes the design** run as one undo step named `Agent: …` and answer the',
    'features whose status is `error` or `warning` after the recompute (`problems`).',
    '',
  ];
  for (const tool of toolDefinitions()) {
    const schema = tool.inputSchema as JsonSchema;
    lines.push(`## \`${tool.name}\``, '');
    if (CHANGE_TOOLS.has(tool.name as (typeof TOOL_NAMES)[number])) {
      lines.push('**Changes the design.**', '');
    }
    lines.push(tool.description, '');
    const properties = Object.entries(schema.properties ?? {});
    if (properties.length === 0) {
      lines.push('No inputs.', '');
      continue;
    }
    lines.push('| Input | Type | Required | What it is |', '| --- | --- | --- | --- |');
    for (const [name, property] of properties) {
      const required = schema.required?.includes(name)
        ? 'yes'
        : property.default !== undefined
          ? `default \`${JSON.stringify(property.default)}\``
          : 'no';
      const type = name === 'shapes' ? 'shape[]' : typeOf(property);
      lines.push(
        `| \`${name}\` | ${cell(`\`${type}\``)} | ${required} | ${cell(property.description ?? '')} |`,
      );
    }
    lines.push('');
    const shapeSchema = schema.properties?.shapes?.items;
    if (shapeSchema && !Array.isArray(shapeSchema)) {
      lines.push('Each shape is one of:', '', ...shapes(shapeSchema), '');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}
