interface Json {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  const?: unknown;
  items?: Json | Json[];
  prefixItems?: Json[];
  anyOf?: Json[];
  oneOf?: Json[];
  properties?: Record<string, Json>;
  required?: string[];
  additionalProperties?: Json | boolean;
  minItems?: number;
  maxItems?: number;
}

